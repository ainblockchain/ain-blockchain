// 인증망 설정 생성기 — 실제로 시험에 사용한 설정을 그대로 재생성한다.
// 실행 (ain-blockchain 저장소 루트에서):
//   node <harness>/make-cert-config.js [name=cert-10-nodes] [epochMs=1000] [bandwidthBudgetPerBlock=1000000]
// 3-nodes 템플릿(min_stake 10,000,000 · genesis 계정 10)을 복사한 뒤 아래를 고친다:
//   - 검증자 10 (genesis_accounts.json others[0..9]) · min/max validators 5/10
//   - others[5..9] 잔액이 1,000,000 이므로 스테이크·min_stake_for_proposer 를 1,000,000 으로 통일
//     (스테이크 < min_stake 면 검증자 목록이 비어 블록 1이 생성되지 않음)
//   - num_genesis_accounts 20 (검증자 10 + 시험 계정 others[10..19])
//   - epoch_ms · bandwidth_budget_per_block · min_gas_price 1
//   - 템플릿의 genesis_block.json.gz 를 제거하고 createGenesisBlock.js 로 재생성 (기존 파일이 있으면 생성기가 거부함)
const fs = require('fs');
const { execSync } = require('child_process');

const NAME = process.argv[2] || 'cert-10-nodes';
const EPOCH_MS = parseInt(process.argv[3] || '1000', 10);
const BANDWIDTH = parseInt(process.argv[4] || '1000000', 10);
const DIR = `blockchain-configs/${NAME}`;
if (!fs.existsSync('blockchain-configs/3-nodes')) throw new Error('run from the ain-blockchain repo root');

fs.rmSync(DIR, { recursive: true, force: true });
fs.cpSync('blockchain-configs/3-nodes', DIR, { recursive: true });
fs.rmSync(`${DIR}/genesis_block.json.gz`, { force: true });

const params = JSON.parse(fs.readFileSync(`${DIR}/blockchain_params.json`));
const accounts = JSON.parse(fs.readFileSync('blockchain-configs/base/genesis_accounts.json'));
const validators = accounts.others.slice(0, 10);

params._description = `Certification network: 10 validators, epoch ${EPOCH_MS} ms, bandwidth ${BANDWIDTH}/block (generated by make-cert-config.js)`;
params.consensus.min_num_validators = 5;
params.consensus.max_num_validators = 10;
params.consensus.min_stake_for_proposer = 1000000;
params.consensus.max_stake_for_proposer = 10000000;
params.consensus.genesis_proposer_whitelist = {};
params.consensus.genesis_validator_whitelist = {};
params.consensus.genesis_validators = {};
for (const v of validators) {
  params.consensus.genesis_proposer_whitelist[v.address] = true;
  params.consensus.genesis_validator_whitelist[v.address] = true;
  params.consensus.genesis_validators[v.address] = { stake: 1000000, proposal_right: true };
}
params.genesis.epoch_ms = EPOCH_MS;
params.genesis.num_genesis_accounts = 20;
params.resource.bandwidth_budget_per_block = BANDWIDTH;
params.resource.min_gas_price = 1;
fs.writeFileSync(`${DIR}/blockchain_params.json`, JSON.stringify(params, null, 2));

execSync(`BLOCKCHAIN_CONFIGS_DIR=${DIR} node tools/genesis-file/createGenesisBlock.js`, { stdio: 'inherit' });
if (!fs.existsSync(`${DIR}/genesis_block.json.gz`)) throw new Error('genesis block was not generated');
console.log(`OK ${DIR}: validators=${validators.length} epoch_ms=${EPOCH_MS} bandwidth=${BANDWIDTH}`);
validators.forEach((v, i) => console.log(` ${i}: ${v.address} balance=${v.balance}`));
